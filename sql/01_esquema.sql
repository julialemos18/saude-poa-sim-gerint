-- ---------------------------------------------------------------------
-- 2. PACIENTE
-- id_origem guarda o identificador cifrado original (nunca é sobrescrito).
-- id_confiavel = FALSE para nulos e para IDs suspeitos (ex.: o ID que
-- aparece em dezenas de milhares de linhas).
-- ---------------------------------------------------------------------
CREATE TABLE paciente (
    id_paciente  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem    TEXT,
    fonte        TEXT    NOT NULL CHECK (fonte IN ('GERINT', 'SIM')),
    id_confiavel BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_confiavel_exige_id
        CHECK (NOT id_confiavel OR id_origem IS NOT NULL)
);

-- Um ID marcado como confiável só pode existir uma vez por fonte.
CREATE UNIQUE INDEX uq_paciente_id_confiavel
    ON paciente (fonte, id_origem)
    WHERE id_confiavel;

-- ---------------------------------------------------------------------
-- 3. SOLICITAÇÃO DE INTERNAÇÃO (GERINT)
-- grupo_cid = categoria CID de 3 caracteres (ex.: J180 -> J18).
-- horas_na_fila_original guarda o valor da fonte (inconsistente).
-- dias_ate_autorizacao = data_autorizacao - data_solicitacao.
-- ---------------------------------------------------------------------
CREATE TABLE solicitacao_internacao (
    id_solicitacao           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente              BIGINT   NOT NULL REFERENCES paciente (id_paciente),
    data_solicitacao         DATE     NOT NULL,
    data_autorizacao         DATE,
    data_internacao          DATE,
    sexo                     TEXT     REFERENCES dom_sexo (valor),
    idade                    SMALLINT CHECK (idade BETWEEN 0 AND 120),
    municipio_residencia     TEXT,
    solicitante              TEXT     NOT NULL,
    municipio_solicitante    TEXT,
    executante               TEXT,
    central_regulacao_origem TEXT,
    codigo_cid               TEXT     CHECK (codigo_cid ~ '^[A-Z][0-9]{2}[0-9A-Z]?$'),
    grupo_cid                TEXT     CHECK (grupo_cid  ~ '^[A-Z][0-9]{2}$'),
    carater                  TEXT     NOT NULL REFERENCES dom_carater (valor),
    tipo_internacao          TEXT     CHECK (tipo_internacao IN ('PRÓPRIA', 'NÃO PRÓPRIA')),
    tipo_leito               TEXT     NOT NULL REFERENCES dom_tipo_leito (valor),
    horas_na_fila_original   INTEGER,
    dias_ate_autorizacao     INTEGER  CHECK (dias_ate_autorizacao >= 0),
    fila_inconsistente       BOOLEAN  NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_autorizacao_apos_solicitacao
        CHECK (data_autorizacao IS NULL OR data_autorizacao >= data_solicitacao),
    CONSTRAINT ck_dias_coerentes
        CHECK (dias_ate_autorizacao IS NULL
               OR dias_ate_autorizacao = data_autorizacao - data_solicitacao)
);

-- ---------------------------------------------------------------------
-- 4. ÓBITO (SIM)
-- id_paciente é UNIQUE: no máximo um óbito por paciente.
-- data_obito e data_nascimento: dia 01 (a fonte só tem mês/ano).
-- ---------------------------------------------------------------------
CREATE TABLE obito (
    id_obito                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente               BIGINT   NOT NULL UNIQUE REFERENCES paciente (id_paciente),
    data_obito                DATE     NOT NULL,
    data_nascimento           DATE,
    idade_obito               SMALLINT CHECK (idade_obito BETWEEN 0 AND 120),
    sexo                      TEXT     REFERENCES dom_sexo (valor),
    raca                      TEXT     REFERENCES dom_raca (valor),
    escolaridade              TEXT     REFERENCES dom_escolaridade (valor),
    gestacao                  TEXT     CHECK (gestacao IN (
                                  'MENOS DE 22 SEM', 'DE 22 A 27 SEM', 'DE 28 A 31 SEM',
                                  'DE 32 A 36 SEM',  'DE 37 A 41 SEM', 'IGNORADO')),
    gravidez                  TEXT     CHECK (gravidez IN ('ÚNICA', 'DUPLA', 'TRIPLA OU MAIS')),
    tipo_obito                TEXT     NOT NULL CHECK (tipo_obito IN ('FETAL', 'NÃO FETAL')),
    circunstancia_obito       TEXT     REFERENCES dom_circunstancia (valor),
    cid_causa_basica          TEXT     CHECK (cid_causa_basica ~ '^[A-Z][0-9]{2}[0-9A-Z]?$'),
    grupo_cid                 TEXT     CHECK (grupo_cid ~ '^[A-Z][0-9]{2}$'),
    obito_prematuro           BOOLEAN,
    obito_mulher_idade_fertil BOOLEAN,
    CONSTRAINT ck_nascimento_antes_obito
        CHECK (data_nascimento IS NULL OR data_nascimento <= data_obito)
);

-- ---------------------------------------------------------------------
-- 5. VÍNCULO SINTÉTICO (resultados EXPERIMENTAIS)
-- id_paciente   = paciente do GERINT a quem se atribui um óbito sintético
-- id_obito      = registro do SIM atribuído a esse paciente
-- id_solicitacao= solicitação usada como referência na regra (opcional)
-- Não prova que são a mesma pessoa; é só para demonstrar as consultas.
-- ---------------------------------------------------------------------
CREATE TABLE vinculo_sintetico (
    id_vinculo           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente          BIGINT NOT NULL UNIQUE REFERENCES paciente (id_paciente),
    id_obito             BIGINT NOT NULL UNIQUE REFERENCES obito (id_obito),
    id_solicitacao       BIGINT REFERENCES solicitacao_internacao (id_solicitacao),
    regra                TEXT   NOT NULL,
    data_obito_sintetica DATE,
    criado_em            TIMESTAMP NOT NULL DEFAULT now()
);